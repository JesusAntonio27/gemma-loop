def record_request_id(record: Mapping[str, Any]) -> str:
    """Trace id of a raw row (Modal main-run rows have no ``request_id``)."""

    stored = record.get("request_id")
    if stored:
        return str(stored)
    return local.stage0_request_id(
        str(record["problem_id"]), int(record.get("sample_index") or 0)
    )


def make_math_verify_fn(
    *, use_math_verify: bool = True
) -> Callable[[Mapping[str, Any], Mapping[str, Any]], tuple[Any, Any]]:
    """The registered math verifier (math-verify OR AIME/integer normalise)."""

    from gemmaloop.stage0.grader import grade_math

    def verify(
        sample: Mapping[str, Any], problem: Mapping[str, Any]
    ) -> tuple[Any, Any]:
        if str(problem.get("kind") or "") != D1_KIND:
            return None, None
        result = grade_math(
            str(sample.get("completion") or sample.get("content") or ""),
            str(problem.get("answer") or ""),
            use_math_verify=bool(use_math_verify),
        )
        return result.correct, result.to_dict()

    return verify


def evaluate_record(
    record: Mapping[str, Any],
    problem: Mapping[str, Any],
    *,
    tokenizer: Any = None,
    token_counter: Callable[[str], int] | None = None,
    renderer: Callable[[list[dict[str, Any]]], int] | None = None,
    verify_fn: Callable[[Mapping[str, Any], Mapping[str, Any]], Any] | None = None,
    max_length: int = MAX_LENGTH,
    min_reasoning_share: float = MIN_REASONING_SHARE,
) -> local.SampleVerdict:
    """Apply the registered Stage 0 filter and, when it passes, verify math."""

    return local.evaluate_sample(
        record,
        problem,
        tokenizer=tokenizer,
        token_counter=token_counter,
        renderer=renderer,
        max_length=int(max_length),
        min_reasoning_share=float(min_reasoning_share),
        verify_fn=verify_fn,
    )


def _trace_row(
    record: Mapping[str, Any],
    problem: Mapping[str, Any],
    verdict: local.SampleVerdict,
    *,
    d1_split: str,
) -> dict[str, Any]:
    row = local.trace_record(record, problem, verdict)
    grade = verdict.grade or {}
    row.update(
        {
            "request_id": record_request_id(record),
            "d1_split": d1_split,
            "correct": True,
            "decided_by": grade.get("decided_by"),
            "verifier_method": grade.get("method"),
            "max_new_tokens": int(record.get("max_new_tokens") or 0),
            "engine_cap": int(record.get("engine_cap") or 0),
            "prompt_tokens": int(record.get("prompt_tokens") or 0),
        }
    )
    return row


def _outcome_row(
    record: Mapping[str, Any],
    problem: Mapping[str, Any],
    verdict: local.SampleVerdict,
    *,
    d1_split: str,
) -> dict[str, Any]:
    row = local.sample_grade_row(record, problem, verdict)
    row.update(
        {
            "request_id": record_request_id(record),
            "d1_split": d1_split,
            "engine": record.get(D1_ENGINE_FIELD),
            "model_revision": record.get("model_revision"),
            "max_new_tokens": int(record.get("max_new_tokens") or 0),
            "engine_cap": int(record.get("engine_cap") or 0),
        }
    )
    return row


def _empty_split_counts(problems: int, requests: int) -> dict[str, Any]:
    return {
        "problems_input": int(problems),
        "requests_expected": int(requests),
        "problems_sampled": 0,
        "problems_with_any_kept": 0,
        "problems_verified_correct": 0,
        "retained_traces": 0,
        "samples_input": 0,
        "samples_kept": 0,
        "samples_verified_correct": 0,
        "problems_missing_samples": 0,
        "problems_without_verified_trace": 0,
    }


def build_corpus(
    records: Iterable[Mapping[str, Any]],
    partition: D1Partition,
    *,
    tokenizer: Any = None,
    token_counter: Callable[[str], int] | None = None,
    renderer: Callable[[list[dict[str, Any]]], int] | None = None,
    verify_fn: Callable[[Mapping[str, Any], Mapping[str, Any]], Any] | None = None,
    max_length: int = MAX_LENGTH,
    min_reasoning_share: float = MIN_REASONING_SHARE,
    samples_per_problem: int = D1_SAMPLES_PER_PROBLEM,
) -> dict[str, Any]:
    """Evaluate every raw sample, select one trace per problem and count.

    Returns ``{"traces": [...], "outcomes": [...], "counts": {...}}``.  No file
    is written; :func:`write_corpus` freezes the result.
    """

    problems_by_id = {
        str(problem["problem_id"]): problem for problem in partition.problems
    }
    split_by_id = {
        str(problem["problem_id"]): name
        for name, rows in (("fit", partition.fit), ("test", partition.test))
        for problem in rows
    }

    grouped: dict[str, list[tuple[dict[str, Any], local.SampleVerdict]]] = defaultdict(list)
    seen_request_ids: set[str] = set()
    unknown_records = 0
    duplicate_records = 0
    engine_counts: Counter[str] = Counter()
    model_revisions: Counter[str] = Counter()

    for raw in records:
        record = dict(raw)
        problem_id = str(record.get("problem_id") or "")
        problem = problems_by_id.get(problem_id)
        if problem is None:
            unknown_records += 1
            continue
        request_id = record_request_id(record)
        if request_id in seen_request_ids:
            duplicate_records += 1
            continue
        seen_request_ids.add(request_id)
        verdict = evaluate_record(
            record,
            problem,
            tokenizer=tokenizer,
            token_counter=token_counter,
            renderer=renderer,
            verify_fn=verify_fn,
            max_length=max_length,
            min_reasoning_share=min_reasoning_share,
        )
        grouped[problem_id].append((record, verdict))
        engine_counts[str(record.get(D1_ENGINE_FIELD) or "unknown")] += 1
        model_revisions[str(record.get("model_revision") or "unknown")] += 1

    outcomes: list[dict[str, Any]] = []
    traces: list[dict[str, Any]] = []
    drop_counts: Counter[str] = Counter()
    split_counts = {
        name: _empty_split_counts(
            len(rows), len(rows) * int(samples_per_problem)
        )
        for name, rows in (("fit", partition.fit), ("test", partition.test))
    }
    samples_input = samples_kept = samples_correct = 0

    for problem_id in sorted(grouped):
        problem = problems_by_id[problem_id]
        split = split_by_id[problem_id]
        items = sorted(
            grouped[problem_id],
            key=lambda item: int(item[0].get("sample_index") or 0),
        )
        stats = split_counts[split]
        stats["problems_sampled"] += 1
        stats["samples_input"] += len(items)
        samples_input += len(items)
        if len(items) != int(samples_per_problem):
            stats["problems_missing_samples"] += 1

        any_kept = False
        chosen: tuple[dict[str, Any], local.SampleVerdict] | None = None
        for record, verdict in items:
            outcomes.append(_outcome_row(record, problem, verdict, d1_split=split))
            if verdict.kept:
                any_kept = True
                samples_kept += 1
                stats["samples_kept"] += 1
            else:
                drop_counts[str(verdict.drop_reason or "unknown")] += 1
            if verdict.kept and verdict.correct is True:
                samples_correct += 1
                stats["samples_verified_correct"] += 1
                if chosen is None:
                    chosen = (record, verdict)
        if any_kept:
            stats["problems_with_any_kept"] += 1
        if chosen is None:
            stats["problems_without_verified_trace"] += 1
            continue
        stats["problems_verified_correct"] += 1
        record, verdict = chosen
        traces.append(_trace_row(record, problem, verdict, d1_split=split))

    for split in split_counts:
        split_counts[split]["retained_traces"] = sum(
            1 for trace in traces if trace["d1_split"] == split
        )

    traces.sort(key=lambda row: (row["d1_split"], str(row["problem_id"])))
    outcomes.sort(
        key=lambda row: (str(row["problem_id"]), int(row.get("sample_index") or 0))
    )

    counts = {
        "samples_input": samples_input,
        "samples_kept": samples_kept,
        "samples_verified_correct": samples_correct,
        "dropped_by_reason": dict(sorted(drop_counts.items())),
        "retained_traces": len(traces),
        "unknown_records": unknown_records,
        "duplicate_records": duplicate_records,
        "engines": dict(sorted(engine_counts.items())),
        "model_revisions": dict(sorted(model_revisions.items())),
        "splits": split_counts,
    }
    return {
        "traces": traces,
        "outcomes": outcomes,
        "counts": counts,
        "parameters": {
            "samples_per_problem": int(samples_per_problem),
            "max_length": int(max_length),
            "min_reasoning_share": float(min_reasoning_share),
        },
    }


