# ---------------------------------------------------------------------------
# Registered corpus constants
# ---------------------------------------------------------------------------
D1_KIND = "math"
D1_FIT_BUCKETS: tuple[int, int] = (60, 61)
D1_TEST_BUCKETS: tuple[int, int] = (62, 69)
D1_BUCKETS: tuple[int, int] = (60, 69)
D1_SPLITS: dict[str, tuple[int, int]] = {
    "fit": D1_FIT_BUCKETS,
    "test": D1_TEST_BUCKETS,
}
D1_SAMPLES_PER_PROBLEM = 4
D1_MIN_FIT_VERIFIED_PROBLEMS = 20
D1_MIN_TEST_VERIFIED_PROBLEMS = 40
D1_DATASET_KIND = "prereg_v1_data_d1"
D1_VERSION = 1
D1_SELECTION_RULE = (
    "per problem, the lowest sample_index among samples that pass the "
    "registered Stage 0 filter and are verified correct; exactly one "
    "retained trace per problem"
)
D1_TRACE_ID_RULE = "{problem_id}:{sample_index}"
# Engine strings written by the two registered backends.  The per-row value is
# authoritative; these are only used for reporting.
D1_MODAL_ENGINE = "vllm==0.30.0"
D1_LOCAL_ENGINE = local.ENGINE
D1_ENGINE_FIELD = "engine"


# ---------------------------------------------------------------------------
# Problem selection
# ---------------------------------------------------------------------------
def bucket_of(problem: Mapping[str, Any]) -> int:
    """Bucket of a pool row, preferring the frozen field over a recomputation."""

    if problem.get("bucket") is not None:
        return int(problem["bucket"])
    return int(bucket_for(str(problem["problem_id"])))


def d1_split_for_bucket(bucket: int) -> str | None:
    """Return ``"fit"``, ``"test"`` or ``None`` for a bucket number."""

    bucket = int(bucket)
    for name, (low, high) in D1_SPLITS.items():
        if low <= bucket <= high:
            return name
    return None


def is_d1_problem(problem: Mapping[str, Any]) -> bool:
    """True for the registered D1 corpus: a math problem in bucket 60-69."""

    return (
        str(problem.get("kind") or "") == D1_KIND
        and d1_split_for_bucket(bucket_of(problem)) is not None
    )


def input_bucket_counts(
    problems: Iterable[Mapping[str, Any]],
) -> dict[str, dict[str, Any]]:
    """Pre-verification bucket populations, by kind, for the addendum.

    The preregistration names the realized inputs (90 problems in 60-61 and
    396 in 62-69) separately from the retained D1 rows; freezing the full
    kind composition makes the math-only exclusion auditable.
    """

    by_split: dict[str, list[Mapping[str, Any]]] = {name: [] for name in D1_SPLITS}
    for problem in problems:
        split = d1_split_for_bucket(bucket_of(problem))
        if split is not None:
            by_split[split].append(problem)
    return {
        name: {
            "total": len(rows),
            "by_kind": dict(
                sorted(Counter(str(row.get("kind") or "") for row in rows).items())
            ),
        }
        for name, rows in by_split.items()
    }


@dataclass(frozen=True)
class D1Partition:
    """The frozen fit/test problem split, sorted by problem id."""

    fit: tuple[dict[str, Any], ...]
    test: tuple[dict[str, Any], ...]

    @property
    def problems(self) -> list[dict[str, Any]]:
        return [*self.fit, *self.test]

    @property
    def counts(self) -> dict[str, int]:
        return {"fit": len(self.fit), "test": len(self.test), "total": len(self.problems)}

    def split_of(self, problem_id: str) -> str | None:
        for name, rows in (("fit", self.fit), ("test", self.test)):
            if any(str(row["problem_id"]) == str(problem_id) for row in rows):
                return name
        return None


def partition_d1_problems(
    problems: Iterable[Mapping[str, Any]],
) -> D1Partition:
    """Select the D1 math problems and split them into fit (60-61) and test.

    Rows of other kinds are excluded (never verified for this corpus) and rows
    outside buckets 60-69 are excluded.  Duplicate problem ids are refused so a
    resumed pool cannot silently double-count a problem.
    """

    fit: list[dict[str, Any]] = []
    test: list[dict[str, Any]] = []
    seen: set[str] = set()
    for problem in problems:
        if str(problem.get("kind") or "") != D1_KIND:
            continue
        bucket = bucket_of(problem)
        split = d1_split_for_bucket(bucket)
        if split is None:
            continue
        problem_id = str(problem["problem_id"])
        if problem_id in seen:
            raise ValueError(f"duplicate D1 problem id: {problem_id!r}")
        seen.add(problem_id)
        row = dict(problem)
        (fit if split == "fit" else test).append(row)
    fit.sort(key=lambda row: str(row["problem_id"]))
    test.sort(key=lambda row: str(row["problem_id"]))
    return D1Partition(fit=tuple(fit), test=tuple(test))


def d1_targets(
    partition: D1Partition,
    *,
    samples_per_prompt: int = D1_SAMPLES_PER_PROBLEM,
) -> list[local.Target]:
    """The ``local.Target`` objects the registered sampler executes.

    The target caps are the realized math counts, so every selected problem is
    sampled exactly once; a shortfall is detected later by the addendum's
    minimum-count check, never by borrowing or regenerating.
    """

    if int(samples_per_prompt) != D1_SAMPLES_PER_PROBLEM:
        raise ValueError(
            f"D1 registers {D1_SAMPLES_PER_PROBLEM} samples per problem, "
            f"got {samples_per_prompt!r}"
        )
    return [
        local.Target(
            "d1_fit",
            D1_FIT_BUCKETS[0],
            D1_FIT_BUCKETS[1],
            len(partition.fit),
            verified=True,
            samples_per_prompt=D1_SAMPLES_PER_PROBLEM,
        ),
        local.Target(
            "d1_test",
            D1_TEST_BUCKETS[0],
            D1_TEST_BUCKETS[1],
            len(partition.test),
            verified=True,
            samples_per_prompt=D1_SAMPLES_PER_PROBLEM,
        ),
    ]


def request_ids(
    partition: D1Partition,
    *,
    samples_per_problem: int = D1_SAMPLES_PER_PROBLEM,
) -> list[str]:
    """Every registered ``{problem_id}:{sample_index}`` trace id."""

    return [
        local.stage0_request_id(str(problem["problem_id"]), index)
        for problem in partition.problems
        for index in range(int(samples_per_problem))
    ]


