"""D1 corpus support: the registered post-tag, pre-pilot data obligation.

The pre-registration (``prereg/prereg.yaml``, D1 ``dial_family`` entry) makes
O's dedicated sampling of the NLL/KL buckets 60-61 (temperature fit) and 62-69
(scored test) an explicit ``prereg-v1-data`` obligation.  The corpus is:

* **math only** -- code is excluded because no hidden-test harness is
  registered for this corpus, chat is excluded by the registered contract;
* four samples per problem with the registered Stage 0 sampling
  (T=1.0, top_p=0.95, top_k=64, thinking on, max_new_tokens 32768) and the
  Stage 0 rendered-length filter of 8192 tokens;
* generated by the registered Stage 0 data sampler (Modal stock vLLM when
  approved, otherwise the local padded adaptive-batch HF engine); the engine is
  recorded per row;
* the lowest-index sample that passes the Stage 0 filter *and* is verified
  correct (math via math-verify under the registered OR rule) is the single
  retained trace per problem.

This module is additive: it reuses :mod:`gemmaloop.stage0.local` (the registered
sampler/filter), :mod:`gemmaloop.stage0.pool` (bucket rule) and
:mod:`gemmaloop.stage0.postprocess` (the filter) without editing them.  The
frozen v3r index binds those existing modules, so all D1-specific code lives
here and in ``scripts/sample_d1.py``.

The pure helpers are driven by CPU tests with fake records, tokenizers and
verifiers; no model, Modal or network access happens at import time.
"""

from __future__ import annotations

