def _sha256_file(path: Path) -> str:
    digest = hashlib.sha256()
    with Path(path).open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def build_addendum(
    *,
    pool_dir: Path,
    pool_manifest: Mapping[str, Any],
    pool_problems_sha256: str,
    partition: D1Partition,
    corpus: Mapping[str, Any],
    model_id: str,
    model_revision: str,
    verifiers: Mapping[str, Any],
    input_counts: Mapping[str, Mapping[str, Any]] | None = None,
    created: str | None = None,
) -> dict[str, Any]:
    """Assemble the fields the ``prereg-v1-data`` addendum must freeze."""

    counts = dict(corpus["counts"])
    splits = counts["splits"]
    fit_min = D1_MIN_FIT_VERIFIED_PROBLEMS
    test_min = D1_MIN_TEST_VERIFIED_PROBLEMS
    fit_verified = int(splits["fit"]["problems_verified_correct"])
    test_verified = int(splits["test"]["problems_verified_correct"])
    minima_ok = fit_verified >= fit_min and test_verified >= test_min
    engine_counts = dict(counts.get("engines") or {})
    return {
        "kind": D1_DATASET_KIND,
        "version": D1_VERSION,
        "status": "verified_pending_freeze",
        "created": created or datetime.now(timezone.utc).isoformat(),
        "post_tag_obligation": "prereg-v1-data (after the prereg-v1 tag, before the pilot)",
        "pool": {
            "dir": str(pool_dir),
            "manifest_sha256": str(pool_manifest.get("manifest_sha256")),
            "problems_sha256": str(pool_problems_sha256),
        },
        "data": {
            "kind_filter": "math only; code and chat excluded",
            "bucket_rule": "bucket = int(sha256(problem_id), 16) % 100, seed 0",
            "fit_bucket": "60-61",
            "test_bucket": "62-69",
            "samples_per_problem": D1_SAMPLES_PER_PROBLEM,
            "requests_expected": {
                "fit": len(partition.fit) * D1_SAMPLES_PER_PROBLEM,
                "test": len(partition.test) * D1_SAMPLES_PER_PROBLEM,
                "total": len(partition.problems) * D1_SAMPLES_PER_PROBLEM,
            },
            "problem_counts": {
                "fit": len(partition.fit),
                "test": len(partition.test),
                "total": len(partition.problems),
            },
            "input_counts": (
                {name: dict(value) for name, value in input_counts.items()}
                if input_counts is not None
                else {}
            ),
            "retained_rule": (
                "no borrowing, regeneration, relaxation or post-result "
                "substitution; only the frozen retained trace per problem is scored"
            ),
        },
        "sampling": {
            "temperature": 1.0,
            "top_p": 0.95,
            "top_k": 64,
            "enable_thinking": True,
            "max_new_tokens": 32768,
            "stage0_rendered_max_length": MAX_LENGTH,
            "filter": (
                "finish_reason=stop; thought channel closed; non-empty answer; "
                "rendered tokens <= 8192; reasoning share >= 0.75 (math)"
            ),
            "registered_modules": {
                "sampler": "gemmaloop.stage0.local / scripts/modal_stage0.py",
                "filter": "gemmaloop.stage0.postprocess.keep_reason",
            },
        },
        "model": {"id": str(model_id), "revision": str(model_revision)},
        "engine": {
            "per_row_field": D1_ENGINE_FIELD,
            "counts": engine_counts,
            "registered": {
                "modal": {
                    "engine": D1_MODAL_ENGINE,
                    "max_new_tokens": 32768,
                },
                "local": {
                    "engine": D1_LOCAL_ENGINE,
                    "budget_rule": "max_length - rendered_prompt_tokens",
                    "note": (
                        "the registered local budget keeps exactly the samples a "
                        "32768-token run keeps after the 8192 rendered-length filter"
                    ),
                },
            },
            "note": "the data-generation engine is recorded per row and is not an evaluation engine",
        },
        "verifiers": dict(verifiers),
        "counts": {
            **counts,
            "problems_verified_correct": {
                "fit": fit_verified,
                "test": test_verified,
                "total": fit_verified + test_verified,
            },
            "minimums": {
                "fit": fit_min,
                "test": test_min,
                "satisfied": bool(minima_ok),
            },
            "d1_evaluable": bool(minima_ok),
        },
        "selection": {
            "rule": D1_SELECTION_RULE,
            "trace_id_rule": D1_TRACE_ID_RULE,
            "fit_trace_ids": [
                str(trace["request_id"])
                for trace in corpus["traces"]
                if trace["d1_split"] == "fit"
            ],
            "test_trace_ids": [
                str(trace["request_id"])
                for trace in corpus["traces"]
                if trace["d1_split"] == "test"
            ],
        },
        "unevaluable_rule": (
            "if either split has fewer verified problems than its minimum, D1 is "
            "unevaluable with no rejection and no alpha transfer; no borrowing, "
            "regeneration or post-result substitution"
        ),
        "files": {},
        "manifest_sha256": None,
    }


def write_corpus(
    output_dir: Path | str,
    corpus: Mapping[str, Any],
    addendum: Mapping[str, Any],
) -> dict[str, Any]:
    """Write traces, per-sample verifier outcomes and the addendum atomically."""

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    traces_sha = local.write_jsonl_atomic(
        output_dir / "d1_traces.jsonl", corpus["traces"]
    )
    outcomes_sha = local.write_jsonl_atomic(
        output_dir / "d1_verifier_outcomes.jsonl", corpus["outcomes"]
    )
    payload = dict(addendum)
    payload["files"] = {
        "d1_traces.jsonl": {
            "sha256": traces_sha,
            "rows": len(corpus["traces"]),
        },
        "d1_verifier_outcomes.jsonl": {
            "sha256": outcomes_sha,
            "rows": len(corpus["outcomes"]),
        },
    }
    payload.pop("manifest_sha256", None)
    payload["manifest_sha256"] = local.manifest_sha256(payload)
    local.write_json_atomic(output_dir / "d1_data_addendum.json", payload)
    return payload


def verify_frozen_addendum(addendum_path: Path | str) -> dict[str, Any]:
    """Re-check every file hash and the addendum hash; return the addendum."""

    addendum_path = Path(addendum_path)
    payload = json.loads(addendum_path.read_text(encoding="utf-8"))
    if payload.get("kind") != D1_DATASET_KIND:
        raise ValueError(f"{addendum_path}: not a D1 data addendum")
    stored = payload.get("manifest_sha256")
    if not stored or stored != local.manifest_sha256(payload):
        raise ValueError("D1 addendum manifest_sha256 is missing or does not recompute")
    base = addendum_path.parent
    for name, entry in (payload.get("files") or {}).items():
        path = base / name
        if not path.exists():
            raise ValueError(f"D1 addendum file missing: {path}")
        if _sha256_file(path) != entry.get("sha256"):
            raise ValueError(f"D1 addendum file sha256 mismatch: {name}")
        if int(entry.get("rows", -1)) != len(local.read_jsonl(path)):
            raise ValueError(f"D1 addendum file row count mismatch: {name}")
    return payload


# ---------------------------------------------------------------------------
# Modal-compatible derived pool
# ---------------------------------------------------------------------------
def write_d1_pool(
    pool_dir: Path | str,
    output_dir: Path | str,
    *,
    partition: D1Partition | None = None,
) -> tuple[list[dict[str, Any]], dict[str, Any]]:
    """Write a frozen pool containing only the D1 math problems.

    ``scripts/modal_stage0.py`` samples ``problems.jsonl`` from ``--pool-dir``
    and has no bucket/kind selector.  A derived, self-contained pool with the
    same decontamination block and a recomputed manifest therefore lets the
    registered Modal sampler run on exactly the D1 corpus with no edit to that
    bound script.  The original pool is validated before the subset is written.
    """

    source_dir = Path(pool_dir)
    problems, manifest = local.load_pool(source_dir)
    selected_partition = partition or partition_d1_problems(problems)
    selected = selected_partition.problems
    if not selected:
        raise ValueError("the source pool has no D1 math problems in buckets 60-69")

    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    problems_sha = local.write_jsonl_atomic(output_dir / "problems.jsonl", selected)
    source_problems_sha = local.file_sha256(source_dir / "problems.jsonl")

    derived = dict(manifest)
    derived.pop("manifest_sha256", None)
    derived["stage"] = "stage0_d1_pool"
    derived["version"] = 1
    derived["derived_from"] = {
        "pool_dir": str(source_dir),
        "manifest_sha256": str(manifest.get("manifest_sha256")),
        "problems_sha256": source_problems_sha,
    }
    derived["d1"] = {
        "kind": "math",
        "fit_bucket": "60-61",
        "test_bucket": "62-69",
        "samples_per_problem": D1_SAMPLES_PER_PROBLEM,
        "problem_counts": selected_partition.counts,
    }
    derived["counts"] = {
        "total": len(selected),
        "by_kind": {"math": len(selected)},
        "by_split": {"nll_kl": len(selected)},
        "d1_problem_counts": selected_partition.counts,
    }
    derived["artifacts"] = {
        "problems.jsonl": {"sha256": problems_sha, "rows": len(selected)}
    }
    derived["manifest_sha256"] = local.manifest_sha256(derived)
    local.write_json_atomic(output_dir / "manifest.json", derived)
    return selected, derived


