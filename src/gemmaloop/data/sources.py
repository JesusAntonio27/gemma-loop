"""Training data sources and conversation conversion.

The five sources are the mixture from reference 07, section 1.  Weights are
token shares, not row shares.  Every ``SourceSpec`` records the Hugging Face
id, config, split, licence and card URL so the mix manifest is self-describing.

Rows are converted to the OpenAI-style ``messages`` structure that TRL expects.
Reasoning traces (``<think>...</think>`` or Gemma's
``<|channel>thought ... <channel|>``) are moved to the assistant message's
``reasoning`` key: Gemma 4's chat template deletes thinking that is left inside
``content`` (reference 07, trap 4).
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Any, Callable, Iterable

from datasets import load_dataset

_ROW_FILTER = Callable[[dict[str, Any]], str | None]
_LOADER = Callable[[], Iterable[dict[str, Any]]]

_THINK_RE = re.compile(r"<think>(.*?)</think>", re.DOTALL | re.IGNORECASE)
_UNCLOSED_THINK_RE = re.compile(r"^\s*<think>(.*)$", re.DOTALL | re.IGNORECASE)
_CHANNEL_RE = re.compile(
    r"<\|channel>thought\b(.*?)<channel\|>", re.DOTALL | re.IGNORECASE
)
# Some QwQ/OpenThoughts exports use explicit solution delimiters instead of a
# closing think tag.  They are not present in the first shards inspected, but
# accepting them costs nothing and keeps the splitter robust.
_SOLUTION_RE = re.compile(
    r"<\|begin_of_solution\|>(.*?)(?:<\|end_of_solution\|>|$)",
    re.DOTALL | re.IGNORECASE,
)
# Internal marker attached by ``_assistant_message`` when the raw text contains
# a thinking opener without its closer.  ``reasoning_defect`` reads it and the
# mixture drops the row; accepted rows never carry it.
_DATA_DEFECT_KEY = "_data_defect"


@dataclass(frozen=True)
class SourceSpec:
    """Description of one streamed training source."""

    hf_id: str
    config: str | None
    split: str
    license: str
    weight: float
    name: str = ""
    url: str = ""
    revision: str | None = None
    provenance: str = ""
    reasoning: bool = False
    columns: tuple[str, ...] | None = None
    row_filter: _ROW_FILTER | None = field(default=None, compare=False, repr=False)
    loader: _LOADER | None = field(default=None, compare=False, repr=False)

    def __post_init__(self) -> None:
        if not self.name:
            object.__setattr__(self, "name", self.hf_id)
        if not self.url:
            object.__setattr__(self, "url", f"https://huggingface.co/datasets/{self.hf_id}")


