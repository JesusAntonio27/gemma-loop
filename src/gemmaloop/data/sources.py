def iter_rows(
    spec: SourceSpec,
    *,
    seed: int = 0,
    limit_rows: int | None = None,
    shuffle_buffer: int = 0,
) -> Iterable[dict[str, Any]]:
    """Yield rows from a source.

    ``loader`` exists so tests can inject local rows without touching the
    network.  A non-positive ``shuffle_buffer`` keeps the natural stream order;
    the final mixture is shuffled deterministically by ``build_mix``.
    """

    if spec.loader is not None:
        stream = spec.loader()
    else:
        kwargs: dict[str, Any] = {}
        if spec.config is not None:
            kwargs["name"] = spec.config
        if spec.revision is not None:
            kwargs["revision"] = spec.revision
        if spec.columns:
            try:
                stream = load_dataset(
                    spec.hf_id,
                    split=spec.split,
                    streaming=True,
                    columns=list(spec.columns),
                    **kwargs,
                )
            except (TypeError, ValueError):
                stream = load_dataset(
                    spec.hf_id, split=spec.split, streaming=True, **kwargs
                )
        else:
            stream = load_dataset(
                spec.hf_id, split=spec.split, streaming=True, **kwargs
            )
        if shuffle_buffer and shuffle_buffer > 0:
            stream = stream.shuffle(seed=seed, buffer_size=shuffle_buffer)

    for index, row in enumerate(stream):
        if limit_rows is not None and index >= limit_rows:
            break
        yield row


# ---------------------------------------------------------------------------
# Conversation conversion
# ---------------------------------------------------------------------------
def _split_reasoning(text: str) -> tuple[str, str]:
    """Return ``(content, reasoning)`` with thinking blocks removed.

    Verified on real rows (3 streamed rows per source, plus three QwQ-32B OMR
    rows and 3,000 OT3 assistant turns): OpenCodeReasoning, OpenMathReasoning
    and OpenThoughts3 all mark their traces with ``<think>...</think>``.  The
    extra patterns cover Gemma's channel form, an unclosed ``<think>`` and
    QwQ's explicit solution delimiters.
    """

    pieces: list[str] = []

    def capture(match: re.Match[str]) -> str:
        pieces.append(match.group(1).strip())
        return ""

    content = _THINK_RE.sub(capture, text or "")
    content = _CHANNEL_RE.sub(capture, content)

    match = _UNCLOSED_THINK_RE.match(content)
    if match:
        pieces.append(match.group(1).strip())
        content = ""

    match = _SOLUTION_RE.search(content)
    if match:
        prefix = content[: match.start()].strip()
        if prefix:
            pieces.append(prefix)
        content = match.group(1).strip()

    reasoning = "\n".join(piece for piece in pieces if piece).strip()
    return content.strip(), reasoning


def _has_unterminated_reasoning(text: str) -> bool:
    """True when a thinking opener has no matching closer.

    Closed blocks are removed first; any opener that remains is unterminated.
    Both the `` thinking`` and Gemma's ``<|channel>thought`` forms are checked.
    """

    remaining = _THINK_RE.sub("", text or "")
    remaining = _CHANNEL_RE.sub("", remaining)
    return bool(
        re.search(r"<\|channel>thought\b", remaining, re.IGNORECASE)
        or re.search(r"<think\b", remaining, re.IGNORECASE)
    )


def _has_reasoning_opener(text: str) -> bool:
    return bool(
        re.search(r"<\|channel>thought\b", text or "", re.IGNORECASE)
        or re.search(r"<think\b", text or "", re.IGNORECASE)
    )


def _assistant_message(text: str) -> dict[str, Any]:
    raw = str(text or "")
    content, reasoning = _split_reasoning(raw)
    message: dict[str, Any] = {"role": "assistant", "content": content}
    if reasoning:
        message["reasoning"] = reasoning
    if _has_unterminated_reasoning(raw):
        message[_DATA_DEFECT_KEY] = "unterminated_think"
    elif (reasoning or _has_reasoning_opener(raw)) and not content.strip():
        message[_DATA_DEFECT_KEY] = "empty_answer"
    return message


def reasoning_defect(messages: Iterable[dict[str, Any]]) -> str | None:
    """Return the drop criterion for a defective reasoning row, or ``None``.

    A row is rejected when any assistant turn has an unterminated thinking
    block (``unterminated_think``) or when the final assistant turn had a
    thinking trace but no answer left after splitting (``empty_answer``).
    Rows without a thinking trace are unaffected.
    """

    assistants = [
        message
        for message in messages
        if str(message.get("role", "")).lower() == "assistant"
    ]
    if not assistants:
        return None
    for message in assistants:
        if message.get(_DATA_DEFECT_KEY) == "unterminated_think":
            return "unterminated_think"
    final = assistants[-1]
    if final.get(_DATA_DEFECT_KEY) == "empty_answer":
        return "empty_answer"
    return None


def strip_defect_markers(messages: Iterable[dict[str, Any]]) -> None:
    """Remove the internal defect marker before a row is serialised."""

    for message in messages:
        message.pop(_DATA_DEFECT_KEY, None)


def _role(value: str) -> str:
    mapping = {
        "human": "user",
        "user": "user",
        "gpt": "assistant",
        "assistant": "assistant",
        "model": "assistant",
        "system": "system",
        "tool": "tool",
    }
    return mapping.get(str(value).strip().lower(), str(value).strip().lower())


def _from_role_content(pairs: Iterable[tuple[str, str]]) -> list[dict[str, Any]]:
    messages: list[dict[str, Any]] = []
    for role, value in pairs:
        if role == "assistant":
            messages.append(_assistant_message(value))
        else:
            messages.append({"role": role, "content": str(value or "")})
    return messages


def _from_conversations(conversations: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    pairs: list[tuple[str, str]] = []
    for turn in conversations or []:
        role = _role(turn.get("from", turn.get("role", "")))
        value = turn.get("value", turn.get("content", ""))
        pairs.append((role, str(value or "")))
    return _from_role_content(pairs)


def to_messages(row: dict[str, Any], source: str) -> list[dict[str, Any]]:
    """Convert one dataset row to OpenAI-style ``messages``.

    The parser is deliberately permissive about the source name: real sources
    select a known schema, while an unknown name falls back to the row's own
    ``messages``/``conversations``/``input``-``output`` fields.  This keeps the
    unit tests network-free and lets new sources reuse the converter.
    """

    if source in {"ocr", "oci"} or (
        source not in {"omr", "ot3", "chat"} and "input" in row
    ):
        return _from_role_content(
            [
                ("user", str(row.get("input") or "")),
                ("assistant", str(row.get("output") or "")),
            ]
        )

    if source == "omr":
        return _from_role_content(
            [
                ("user", str(row.get("problem") or "")),
                ("assistant", str(row.get("generated_solution") or "")),
            ]
        )

    if source == "ot3" or (source not in {"chat"} and "conversations" in row):
        return _from_conversations(row.get("conversations") or [])

    if "messages" in row:
        pairs: list[tuple[str, str]] = []
        for message in row.get("messages") or []:
            role = _role(message.get("role", message.get("from", "")))
            value = message.get("content", message.get("value", ""))
            pairs.append((role, str(value or "")))
        return _from_role_content(pairs)

    if "conversations" in row:
        return _from_conversations(row.get("conversations") or [])

    return _from_role_content(
        [
            ("user", str(row.get("input") or row.get("prompt") or "")),
            ("assistant", str(row.get("output") or row.get("response") or "")),
        ]
    )


