# Row filters (criteria straight from reference 07, section 1)
# ---------------------------------------------------------------------------
def _ocr_filter(row: dict[str, Any]) -> str | None:
    output = str(row.get("output") or "")
    if not (800 <= len(output) <= 24_000):
        return "ocr_length"
    if not str(row.get("input") or "").strip():
        return "empty"
    return None


def _oci_filter(row: dict[str, Any]) -> str | None:
    try:
        score = float(row.get("average_test_score"))
    except (TypeError, ValueError):
        return "oci_score"
    if score != 1.0:
        return "oci_score"
    if not str(row.get("input") or "").strip():
        return "empty"
    return None


def _omr_filter(row: dict[str, Any]) -> str | None:
    source = str(row.get("problem_source") or "").strip().lower()
    if "amc_aime" in source or source in {"amc", "aime"}:
        return "omr_amc_aime"
    if not str(row.get("problem") or "").strip():
        return "empty"
    return None


def _ot3_filter(row: dict[str, Any]) -> str | None:
    if str(row.get("domain") or "").strip().lower() != "code":
        return "ot3_domain"
    return None


